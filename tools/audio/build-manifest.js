#!/usr/bin/env node
/**
 * Regenerates src/audio/bundledAudio.ts from the files in assets/audio/.
 * Metro only bundles assets referenced by static require() calls, so every
 * recording needs one line there. split-takes.js runs this automatically;
 * run it by hand after adding or deleting clips yourself:
 *
 *   node tools/audio/build-manifest.js
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./takes');

const AUDIO_DIR = path.join(ROOT, 'assets', 'audio');
const OUT = path.join(ROOT, 'src', 'audio', 'bundledAudio.ts');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : /\.(mp3|m4a|wav|aac)$/i.test(e.name) ? [p] : [];
  });
}

function buildManifest() {
  const files = walk(AUDIO_DIR)
    .map((f) => path.relative(AUDIO_DIR, f).split(path.sep).join('/'))
    .sort();
  const lines = files.map((p) => `  '${p}': require('../../assets/audio/${p}'),`);
  const src = `// GENERATED by tools/audio/build-manifest.js — do not edit by hand.
// Maps ContentItem.audio_path → bundled recording. Metro needs static requires.
export const BUNDLED: Record<string, number> = {
${lines.join('\n')}
};
`;
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== src) fs.writeFileSync(OUT, src);
  return files.length;
}

if (require.main === module) {
  console.log(`${buildManifest()} recording(s) → ${path.relative(ROOT, OUT)}`);
}

module.exports = { buildManifest };
